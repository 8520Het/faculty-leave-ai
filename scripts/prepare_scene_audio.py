def get_duration(audio_file):
    exe = imageio_ffmpeg.get_ffmpeg_exe()
    res = subprocess.run([exe, "-i", str(audio_file)], capture_output=True, text=True)
    for line in res.stderr.splitlines():
        if "Duration:" in line:
            # Duration: 00:00:37.44, start: ...
            parts = line.split("Duration:")[1].split(",")[0].strip()
            h, m, s = parts.split(":")
            return float(h)*3600 + float(m)*60 + float(s)
    return 0.0

async def generate():
    durations = {}
    for num, text in SCENES:
        out_file = AUDIO_DIR / f"scene_{num}.mp3"
        print(f"Generating Scene {num} audio...")
        tts = edge_tts.Communicate(text, VOICE, rate="+0%")
        await tts.save(str(out_file))
        dur = get_duration(out_file)
        durations[num] = dur
        print(f"  Scene {num}: {dur:.2f} seconds")

    # Combine into master audio
    exe = imageio_ffmpeg.get_ffmpeg_exe()
    concat_list = AUDIO_DIR / "concat_list.txt"
    with open(concat_list, "w", encoding="utf-8") as f:
        for num, _ in SCENES:
            f.write(f"file 'scene_{num}.mp3'\n")

    master_audio = Path("faculty_leave_ai_indian_voiceover.mp3")
    cmd = [
        exe, "-y", "-f", "concat", "-safe", "0",
        "-i", str(concat_list),
        "-c", "copy",
        str(master_audio)
    ]
    subprocess.run(cmd, check=True)
    total_dur = get_duration(master_audio)
    print(f"\nMaster Indian Voiceover Audio created: {master_audio}")
    print(f"Total Duration: {total_dur:.2f} seconds")

    # Output durations dict
    print("\nScene Durations (seconds):")
    for num, dur in durations.items():
        print(f"Scene {num}: {dur:.2f}s")

if __name__ == "__main__":
    asyncio.run(generate())
